export const toGrid = (d: Drawing): { w: number; h: number; cells: number[] } => ({
  w: d.rows[0].length,
  h: d.rows.length,
  cells: d.rows.flatMap((r) => [...r].map((ch) => (ch === '#' ? 1 : 0))),
});
